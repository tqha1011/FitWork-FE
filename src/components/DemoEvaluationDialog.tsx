import { useEffect, useState } from "react";
import { isCancel } from "axios";
import { Button, Dialog } from "./ui";
import EvaluationResult from "./EvaluationResult";
import {
  getEvaluation,
  getJobOwnerEvaluation,
} from "../services/evaluationService";
import { demoErrorMessage } from "../shared/demoErrorMessage";
import type { EvaluationDetail, JobOwnerEvaluation } from "../types/evaluation";
import type { UserType } from "../types/auth";

export interface DemoResultSelection {
  jobPublicId: string;
  evaluationPublicId: string;
  source: "SAMPLE" | "LIVE";
  applicantName: string;
}
export default function DemoEvaluationDialog({
  selection,
  userType,
  onClose,
}: {
  selection: DemoResultSelection;
  userType: UserType;
  onClose: () => void;
}) {
  const [result, setResult] = useState<EvaluationDetail | JobOwnerEvaluation>();
  const [error, setError] = useState("");
  const [retry, setRetry] = useState(0);
  useEffect(() => {
    const controller = new AbortController();
    const request =
      userType === "COMPANY"
        ? getJobOwnerEvaluation(
            selection.jobPublicId,
            selection.evaluationPublicId,
            controller.signal,
          )
        : getEvaluation(
            selection.jobPublicId,
            controller.signal,
            selection.evaluationPublicId,
          );
    void request
      .then((data) => {
        if (!controller.signal.aborted) setResult(data);
      })
      .catch((error) => {
        if (!controller.signal.aborted && !isCancel(error))
          setError(demoErrorMessage(error));
      });
    return () => controller.abort();
  }, [selection, userType, retry]);
  const source = result?.source ?? selection.source;
  return (
    <Dialog
      open
      title={source === "SAMPLE" ? "Sample result" : "Live AI result"}
      onClose={onClose}
      className="demo-result-dialog"
    >
      <p className="muted">{selection.applicantName}</p>
      <p className="notice demo-result-notice">
        {source === "SAMPLE"
          ? "Prepared example to explore how FitWork explains job fit."
          : "Generated by AI for this demo application."}{" "}
        This result supports human review; it does not make a hiring decision.
      </p>
      {result ? (
        <EvaluationResult result={result} />
      ) : error ? (
        <div className="stack">
          <p role="alert" className="job-error">
            {error}
          </p>
          <Button
            variant="secondary"
            onClick={() => {
              setError("");
              setRetry((value) => value + 1);
            }}
          >
            Retry
          </Button>
        </div>
      ) : (
        <p role="status">Loading evaluation…</p>
      )}
      <div className="dialog-actions">
        <Button variant="secondary" onClick={onClose}>
          Close result
        </Button>
      </div>
    </Dialog>
  );
}
